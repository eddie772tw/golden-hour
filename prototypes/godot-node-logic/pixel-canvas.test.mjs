import assert from 'node:assert/strict';
import {PixelCanvas} from './pixel-canvas.mjs';
const canvas=new PixelCanvas(name=>{throw Error(name);});
canvas.width=2;canvas.height=2;
const ctx=canvas.getContext('2d'),image=ctx.createImageData(2,2);
image.data.set([10,20,30,255,40,50,60,255,70,80,90,255,100,110,120,255]);
ctx.putImageData(image,0,0);
assert.deepEqual(ctx.getImageData(0,0,2,2).data,image.data);
assert.deepEqual([...ctx.getImageData(1,1,2,1).data],[100,110,120,255,0,0,0,0]);
canvas.width=2;
assert.deepEqual([...ctx.getImageData(0,0,2,2).data],Array(16).fill(0));
assert.throws(()=>ctx.fillRect(0,0,1,1),/Canvas2D.fillRect/);
assert.throws(()=>canvas.getContext('webgl2'),/webgl2/);
console.log('PASS: exact RGBA copy/clip/resize; drawing and GPU context calls throw');
const capture=new PixelCanvas(name=>{throw Error(name);},{captureDrawCommands:true});
capture.getContext('2d').fillText('KR-7',8,44);
assert.equal(capture.drawCommands[0].name,'fillText');
assert.throws(()=>capture.getContext('2d').getImageData(0,0,1,1),/requires rasterizer/);
assert.throws(()=>capture.getContext('2d').measureText('x'),/measureText/);
console.log('PASS: optional drawing output captured; unrasterized reads never fabricate pixels');
